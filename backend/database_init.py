def init_database():
    with engine.begin() as connection:
        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS pakistan_cities (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                city_name VARCHAR(150) NOT NULL,
                province VARCHAR(100),
                latitude NUMERIC(9,6) NOT NULL,
                longitude NUMERIC(9,6) NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_city_name
            ON pakistan_cities (city_name)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_city_latitude
            ON pakistan_cities (latitude)
        """))

        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS weather_snapshots (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                city_id BIGINT NOT NULL,
                temperature_c NUMERIC(5,2),
                relative_humidity NUMERIC(5,2),
                apparent_temperature_c NUMERIC(5,2),
                wind_speed_kmh NUMERIC(7,2),
                observed_at TIMESTAMP,
                recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT fk_weather_city
                    FOREIGN KEY (city_id)
                    REFERENCES pakistan_cities(id)
            )
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_weather_city_id
            ON weather_snapshots (city_id)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_weather_observed_at
            ON weather_snapshots (observed_at)
        """))


        insert_city = text("""
            INSERT INTO pakistan_cities
                (city_name, province, latitude, longitude)
            SELECT
                CAST(:name AS VARCHAR(150)),
                CAST(:province AS VARCHAR(100)),
                CAST(:latitude AS NUMERIC(9,6)),
                CAST(:longitude AS NUMERIC(9,6))
            WHERE NOT EXISTS (
                SELECT 1
                FROM pakistan_cities
                WHERE city_name = CAST(:name AS VARCHAR(150))
            )
        """)


        for name, province, latitude, longitude in CITIES:
            connection.execute(
                insert_city,
                {
                    "name": name,
                    "province": province,
                    "latitude": latitude,
                    "longitude": longitude,
                },
            )

    print("PostgreSQL tables initialized and default cities verified.")
